    // Project-generated literal VP8L, not an encoded copy of a downloaded image.
    // One-symbol prefix trees consume no pixel bits; an optional two-symbol red
    // tree supplies a deterministic nonuniform image without allocating RGBA.
    // Container/bit layout: https://developers.google.com/speed/webp/docs/webp_lossless_bitstream_specification
    internal static byte[] CreateLiteralWebP(int width, int height, bool patterned = false)
    {
        if (width is < 1 or > 16384 || height is < 1 or > 16384)
            throw new ArgumentOutOfRangeException(nameof(width));
        int pixelCount = checked(width * height);
        int bitLength = checked(32 + 3 + 5 * 11 + (patterned ? 8 + pixelCount : 0));
        byte[] payload = new byte[1 + ((bitLength + 7) / 8)];
        payload[0] = 0x2f;
        int bitOffset = 8;
        WriteBits((uint)(width - 1), 14);
        WriteBits((uint)(height - 1), 14);
        WriteBits(1, 1); // The constant alpha channel is 127.
        WriteBits(0, 3); // Version zero.
        WriteBits(0, 3); // No transforms, color cache or entropy image.
        WriteTree(59); // Green.
        WriteTree(17, patterned ? (byte)201 : null); // Red.
        WriteTree(91); // Blue.
        WriteTree(127); // Alpha.
        WriteTree(0); // Unused distance tree, no backward references.
        if (patterned)
        {
            for (int y = 0; y < height; y++)
            for (int x = 0; x < width; x++)
                WriteBits((uint)LiteralPatternBit(x, y), 1);
        }

        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream, Encoding.ASCII, leaveOpen: true);
        writer.Write("RIFF"u8);
        writer.Write(4 + 8 + payload.Length + (payload.Length & 1));
        writer.Write("WEBP"u8);
        WriteChunk(writer, "VP8L"u8, payload);
        return stream.ToArray();

        void WriteTree(byte first, byte? second = null)
        {
            WriteBits(1, 1); // Simple prefix tree.
            WriteBits(second.HasValue ? 1u : 0u, 1);
            WriteBits(1, 1); // First symbol uses eight bits, including zero.
            WriteBits(first, 8);
            if (second is byte value)
                WriteBits(value, 8);
        }

        void WriteBits(uint value, int count)
        {
            for (int bit = 0; bit < count; bit++, bitOffset++)
                payload[bitOffset >> 3] |= (byte)(((value >> bit) & 1) << (bitOffset & 7));
        }
    }

    internal static int LiteralPatternBit(int x, int y) =>
        ((x * 17 + y * 29) ^ (x >> 2) ^ (y >> 3)) & 1;

    internal static byte[] WithMetadata(byte[] source, int width, int height,
        byte[]? colorProfile = null, int? orientation = null, bool hasAlpha = false)
    {
        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream, Encoding.ASCII, leaveOpen: true);
        writer.Write("RIFF"u8);
        writer.Write(0);
        writer.Write("WEBP"u8);
        byte[] extendedHeader = new byte[10];
        extendedHeader[0] = (byte)((colorProfile is null ? 0 : 0x20) |
            (orientation is null ? 0 : 0x08) | (hasAlpha ? 0x10 : 0));
        Write24(extendedHeader.AsSpan(4), width - 1);
        Write24(extendedHeader.AsSpan(7), height - 1);
        WriteChunk(writer, "VP8X"u8, extendedHeader);
        if (colorProfile is not null)
            WriteChunk(writer, "ICCP"u8, colorProfile);
        writer.Write(source.AsSpan(12));
        if (orientation is int value)
        {
            // Little-endian TIFF with one SHORT orientation entry, no child IFD.
            byte[] exif = new byte[26];
            "II"u8.CopyTo(exif);
            BinaryPrimitives.WriteUInt16LittleEndian(exif.AsSpan(2), 42);
            BinaryPrimitives.WriteUInt32LittleEndian(exif.AsSpan(4), 8);
            BinaryPrimitives.WriteUInt16LittleEndian(exif.AsSpan(8), 1);
            BinaryPrimitives.WriteUInt16LittleEndian(exif.AsSpan(10), 0x112);
            BinaryPrimitives.WriteUInt16LittleEndian(exif.AsSpan(12), 3);
            BinaryPrimitives.WriteUInt32LittleEndian(exif.AsSpan(14), 1);
            BinaryPrimitives.WriteUInt16LittleEndian(exif.AsSpan(18), checked((ushort)value));
            WriteChunk(writer, "EXIF"u8, exif);
        }
        byte[] result = stream.ToArray();
        BinaryPrimitives.WriteUInt32LittleEndian(result.AsSpan(4), checked((uint)result.Length - 8));
        return result;
    }

    // Project-generated ICC v2/v4 matrix/TRC profile: sRGB primaries adapted to D50,
    // but linear transfer curves. This deliberately changes midtone values, so a
    // decoder that silently ignores ICC cannot pass the integration assertion.
    // Format: https://www.color.org/icc33.pdf and
    // https://www.color.org/specification/ICC1v43_2010-12.pdf (no downloaded profile payload).
    internal static byte[] CreateLinearRgbProfile(bool version4 = false)
    {
        byte[] curve = new byte[14];
        "curv"u8.CopyTo(curve);
        BinaryPrimitives.WriteUInt32BigEndian(curve.AsSpan(8), 1);
        BinaryPrimitives.WriteUInt16BigEndian(curve.AsSpan(12), 0x100);
        byte[] description = ProfileDescription("MarkdownRenderer generated linear RGB", version4);
        byte[] copyright = ProfileCopyright(version4);
        (string Signature, byte[] Data)[] tags =
        [
            ("desc", description), ("cprt", copyright), ("wtpt", Xyz(0.9642, 1, 0.8249)),
            ("rXYZ", Xyz(0.4360747, 0.2225045, 0.0139322)),
            ("gXYZ", Xyz(0.3850649, 0.7168786, 0.0971045)),
            ("bXYZ", Xyz(0.1430804, 0.0606169, 0.7141733)),
            ("rTRC", curve), ("gTRC", curve), ("bTRC", curve),
        ];
        return CreateProfile(tags, version4);
    }

    // The same linear RGB colorimetry represented by an ICC lut16Type, not a
    // matrix/shaper. Eight corners suffice because RGB-to-XYZ is linear. PCS
    // XYZ uses u1Fixed15 values; the input/output tables span the full range.
    internal static byte[] CreateLinearRgbLutProfile(bool version4 = false)
    {
        byte[] lut = new byte[52 + 12 + 48 + 12];
        "mft2"u8.CopyTo(lut);
        lut[8] = 3;
        lut[9] = 3;
        lut[10] = 2;
        for (int axis = 0; axis < 3; axis++)
            BinaryPrimitives.WriteInt32BigEndian(lut.AsSpan(12 + axis * 16), 65536);
        BinaryPrimitives.WriteUInt16BigEndian(lut.AsSpan(48), 2);
        BinaryPrimitives.WriteUInt16BigEndian(lut.AsSpan(50), 2);
        for (int channel = 0; channel < 3; channel++)
        {
            BinaryPrimitives.WriteUInt16BigEndian(lut.AsSpan(52 + channel * 4 + 2), 65535);
            BinaryPrimitives.WriteUInt16BigEndian(lut.AsSpan(112 + channel * 4 + 2), 65535);
        }
        int offset = 64;
        WriteLinearRgbXyzCube(lut.AsSpan(offset, 48));
        return CreateProfile(
        [
            ("desc", ProfileDescription("MarkdownRenderer generated linear RGB LUT", version4)),
            ("cprt", ProfileCopyright(version4)),
            ("wtpt", Xyz(0.9642, 1, 0.8249)),
            ("A2B0", lut), ("A2B1", lut),
        ], version4);
    }

    internal static byte[] CreateLinearRgbMultiStageProfile()
    {
        // lutAToBType: a 32-byte header, three identity B curves, a
        // 2x2x2 16-bit CLUT, and three identity A curves. A-CLUT-B is an
        // allowed processing-element combination (ICC.1 section 10.12).
        // Offset 32 is a valid first-stage location and must
        // not be mistaken for the longer lut16Type header size.
        byte[] lut = new byte[32 + 36 + 20 + 48 + 36];
        "mAB "u8.CopyTo(lut);
        lut[8] = 3;
        lut[9] = 3;
        BinaryPrimitives.WriteUInt32BigEndian(lut.AsSpan(12), 32);
        BinaryPrimitives.WriteUInt32BigEndian(lut.AsSpan(24), 68);
        BinaryPrimitives.WriteUInt32BigEndian(lut.AsSpan(28), 136);
        for (int channel = 0; channel < 3; channel++)
        {
            "curv"u8.CopyTo(lut.AsSpan(32 + channel * 12));
            "curv"u8.CopyTo(lut.AsSpan(136 + channel * 12));
            lut[68 + channel] = 2;
        }
        lut[84] = 2;
        WriteLinearRgbXyzCube(lut.AsSpan(88, 48));
        return CreateProfile(
        [
            ("desc", ProfileDescription("MarkdownRenderer generated linear RGB mAB", version4: true)),
            ("cprt", ProfileCopyright(version4: true)),
            ("wtpt", Xyz(0.9642, 1, 0.8249)),
            ("A2B0", lut), ("A2B1", lut),
        ], version4: true);
    }

    private static void WriteLinearRgbXyzCube(Span<byte> destination)
    {
        int offset = 0;
        for (int red = 0; red < 2; red++)
        for (int green = 0; green < 2; green++)
        for (int blue = 0; blue < 2; blue++)
        {
            double[] xyz =
            [
                red * 0.4360747 + green * 0.3850649 + blue * 0.1430804,
                red * 0.2225045 + green * 0.7168786 + blue * 0.0606169,
                red * 0.0139322 + green * 0.0971045 + blue * 0.7141733,
            ];
            foreach (double value in xyz)
            {
                BinaryPrimitives.WriteUInt16BigEndian(destination[offset..],
                    checked((ushort)Math.Round(value * 32768)));
                offset += 2;
            }
        }
    }

    private static byte[] CreateProfile((string Signature, byte[] Data)[] tags, bool version4)
    {
        int tagOffset = 132 + tags.Length * 12;
        int size = tagOffset + tags.Sum(tag => (tag.Data.Length + 3) & ~3);
        byte[] profile = new byte[size];
        BinaryPrimitives.WriteUInt32BigEndian(profile, checked((uint)size));
        BinaryPrimitives.WriteUInt32BigEndian(profile.AsSpan(8), version4 ? 0x04300000u : 0x02100000u);
        "mntr"u8.CopyTo(profile.AsSpan(12));
        "RGB "u8.CopyTo(profile.AsSpan(16));
        "XYZ "u8.CopyTo(profile.AsSpan(20));
        BinaryPrimitives.WriteUInt16BigEndian(profile.AsSpan(24), 2026);
        BinaryPrimitives.WriteUInt16BigEndian(profile.AsSpan(26), 1);
        BinaryPrimitives.WriteUInt16BigEndian(profile.AsSpan(28), 1);
        "acsp"u8.CopyTo(profile.AsSpan(36));
        "MSFT"u8.CopyTo(profile.AsSpan(40));
        BinaryPrimitives.WriteUInt32BigEndian(profile.AsSpan(64), 1); // relative colorimetric
        Xyz(0.9642, 1, 0.8249).AsSpan(8).CopyTo(profile.AsSpan(68));
        BinaryPrimitives.WriteUInt32BigEndian(profile.AsSpan(128), checked((uint)tags.Length));
        for (int index = 0; index < tags.Length; index++)
        {
            Span<byte> entry = profile.AsSpan(132 + index * 12, 12);
            Encoding.ASCII.GetBytes(tags[index].Signature, entry);
            BinaryPrimitives.WriteUInt32BigEndian(entry[4..], checked((uint)tagOffset));
            BinaryPrimitives.WriteUInt32BigEndian(entry[8..], checked((uint)tags[index].Data.Length));
            tags[index].Data.CopyTo(profile.AsSpan(tagOffset));
            tagOffset += (tags[index].Data.Length + 3) & ~3;
        }
        return profile;
    }

    private static byte[] Xyz(double x, double y, double z)
    {
        byte[] data = new byte[20];
        "XYZ "u8.CopyTo(data);
        BinaryPrimitives.WriteInt32BigEndian(data.AsSpan(8), (int)Math.Round(x * 65536));
        BinaryPrimitives.WriteInt32BigEndian(data.AsSpan(12), (int)Math.Round(y * 65536));
        BinaryPrimitives.WriteInt32BigEndian(data.AsSpan(16), (int)Math.Round(z * 65536));
        return data;
    }

    private static byte[] ProfileDescription(string value, bool version4)
    {
        if (version4)
            return LocalizedString(value);
        byte[] text = Encoding.ASCII.GetBytes(value + '\0');
        byte[] description = new byte[12 + text.Length + 78];
        "desc"u8.CopyTo(description);
        BinaryPrimitives.WriteUInt32BigEndian(description.AsSpan(8), checked((uint)text.Length));
        text.CopyTo(description.AsSpan(12));
        return description;
    }

    private static byte[] ProfileCopyright(bool version4)
    {
        if (version4)
            return LocalizedString("Project-generated test profile; MIT");
        byte[] copyright = new byte[8 + "Project-generated test profile; MIT\0"u8.Length];
        "text"u8.CopyTo(copyright);
        "Project-generated test profile; MIT\0"u8.CopyTo(copyright.AsSpan(8));
        return copyright;
    }

    private static byte[] LocalizedString(string value)
    {
        byte[] text = Encoding.BigEndianUnicode.GetBytes(value);
        byte[] data = new byte[28 + text.Length];
        "mluc"u8.CopyTo(data);
        BinaryPrimitives.WriteUInt32BigEndian(data.AsSpan(8), 1);
        BinaryPrimitives.WriteUInt32BigEndian(data.AsSpan(12), 12);
        "enUS"u8.CopyTo(data.AsSpan(16));
        BinaryPrimitives.WriteUInt32BigEndian(data.AsSpan(20), checked((uint)text.Length));
        BinaryPrimitives.WriteUInt32BigEndian(data.AsSpan(24), 28);
        text.CopyTo(data.AsSpan(28));
        return data;
    }

    private static void Write24(Span<byte> target, int value)
    {
        target[0] = (byte)value;
        target[1] = (byte)(value >> 8);
        target[2] = (byte)(value >> 16);
    }

    private static void WriteChunk(BinaryWriter writer, ReadOnlySpan<byte> type, ReadOnlySpan<byte> payload)
    {
        writer.Write(type);
        writer.Write(payload.Length);
        writer.Write(payload);
        if ((payload.Length & 1) != 0)
            writer.Write((byte)0);
    }

    internal static bool IsValid(MarkdownRaster raster)
    {
        if (raster.WidthPixels != 2 || raster.HeightPixels != 2 || raster.StrideBytes != 8 ||
            raster.LengthBytes != 16 || raster.PixelFormat != MarkdownRasterPixelFormat.Bgra8Premultiplied)
            return false;
        ReadOnlySpan<byte> pixels = raster.Pixels.Span;
        bool hasColor = false;
        for (int offset = 0; offset < pixels.Length; offset += 4)
        {
            if (pixels[offset + 3] != 255)
                return false;
            hasColor |= pixels[offset] is > 0 and < 255 || pixels[offset + 1] is > 0 and < 255 ||
                pixels[offset + 2] is > 0 and < 255;
        }
        return hasColor;
    }
