        $arguments = @(
            'publish', $consumerProjectPath,
            '-c', 'Release', '-r', $target.Rid,
            ('-p:Platform=' + $target.Platform),
            '--self-contained', 'true',
            ('-p:RestoreAdditionalProjectSources=' + $packageDirectoryA),
            '--disable-build-servers', '-p:UseSharedCompilation=false', '-nr:false',
            '-o', $publishDirectory
        )
        if ($mode -eq 'nativeaot') {
            $arguments += @(
                '-p:PublishAot=true', '-p:PublishSingleFile=false',
                '-p:UseAppHost=true'
            )
        }
        else {
            $arguments += @(
                '-p:PublishAot=false', '-p:PublishTrimmed=true', '-p:TrimMode=full',
                '-p:PublishSingleFile=true', '-p:EnableMsixTooling=true'
            )
        }

        Push-Location $repositoryRoot
        try { Invoke-DotNet $arguments }
        finally { Pop-Location }

        $executable = Join-Path $publishDirectory 'TextMatePackageConsumer.exe'
        if (-not (Test-Path -LiteralPath $executable -PathType Leaf)) {
            throw "$mode $($target.Rid) did not produce a consumer executable."
        }
        if ($mode -eq 'nativeaot' -and (Test-Path -LiteralPath (Join-Path $publishDirectory 'TextMatePackageConsumer.dll') -PathType Leaf)) {
            throw "nativeaot $($target.Rid) published a managed consumer DLL instead of a NativeAOT executable."
        }
        $machine = Get-PeMachine $executable
        if ($machine -ne $target.Machine) {
            throw "$mode $($target.Rid) produced a $machine PE instead of $($target.Machine)."
        }
        $nativeAssets = @(Get-ChildItem -LiteralPath $publishDirectory -Recurse -File -Filter 'libonigwrap.dll')
        $nativeMachine = Get-PeMachine $selectedNative.FullName
        $nativeBytes = $selectedNative.Length
        $nativeSha256 = Get-Sha256 $selectedNative.FullName
        $nativeBundleOccurrences = $null
        if ($mode -eq 'nativeaot') {
            if ($nativeAssets.Count -ne 1) {
                throw "$mode $($target.Rid) contains $($nativeAssets.Count) selected Onigwrap native assets; expected one."
            }
            $nativeMachine = Get-PeMachine $nativeAssets[0].FullName
            if ($nativeMachine -ne $target.Machine) {
                throw "$mode $($target.Rid) selected $nativeMachine Onigwrap instead of $($target.Machine)."
            }
            $nativeBytes = $nativeAssets[0].Length
            $nativeSha256 = Get-Sha256 $nativeAssets[0].FullName
        }
        else {
            if ($nativeAssets.Count -ne 0) {
                throw "$mode $($target.Rid) left $($nativeAssets.Count) loose Onigwrap native assets; expected the payload to be bundled."
            }
            $nativeBundleOccurrences = Get-ByteSequenceCount -HaystackPath $executable -NeedlePath $selectedNative.FullName
            if ($nativeBundleOccurrences -ne 1) {
                throw "$mode $($target.Rid) bundles $nativeBundleOccurrences copies of the selected Onigwrap native payload; expected one."
            }
        }

        $execution = Invoke-CompatibleExecutable `
            -Path $executable `
            -Rid $target.Rid `
            -HostArchitecture $hostArchitecture
        $deployments.Add([pscustomobject][ordered]@{
            mode = $mode
            rid = $target.Rid
            peMachine = $machine
            executableBytes = (Get-Item -LiteralPath $executable).Length
            sha256 = Get-Sha256 $executable
            selectedNativeMachine = $nativeMachine
            selectedNativeBytes = $nativeBytes
            selectedNativeSha256 = $nativeSha256
            selectedNativeBundleOccurrences = $nativeBundleOccurrences
            executed = $execution.executed
            exitCode = $execution.exitCode
            output = $execution.output
            skipReason = $execution.reason
        })
    }
}

