function Invoke-DotNet {
    param([Parameter(Mandatory)][string[]] $Arguments)

    if ($Arguments[0] -eq 'restore') {
        # The evidence source is disposable. Do not require or rewrite its copied
        # lock files, which may have been generated by a different SDK patch.
        $Arguments += @(
            '-p:RestorePackagesWithLockFile=false',
            '-p:RestoreLockedMode=false',
            ("-p:NuGetLockFilePath=$evidenceLockPath")
        )
    }
    & dotnet @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet $($Arguments -join ' ') failed with exit code $LASTEXITCODE."
    }
}

function Get-Sha256 {
    param([Parameter(Mandatory)][string] $Path)

    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Get-ByteSequenceCount {
    param(
        [Parameter(Mandatory)][string] $HaystackPath,
        [Parameter(Mandatory)][string] $NeedlePath
    )

    # Single-file publishing embeds native libraries in the app bundle rather
    # than leaving them beside the executable. Count the exact payload bytes so
    # the release gate still proves that precisely the selected RID asset was
    # bundled, without depending on runtime extraction implementation details.
    $haystack = [IO.File]::ReadAllBytes($HaystackPath)
    $needle = [IO.File]::ReadAllBytes($NeedlePath)
    if ($needle.Length -eq 0) {
        throw "Cannot search for an empty native payload."
    }

    if (-not ('MarkdownRendererNativeBundleProbe' -as [type])) {
        Add-Type -TypeDefinition @'
using System;
public static class MarkdownRendererNativeBundleProbe
{
    public static int Count(byte[] haystack, byte[] needle)
    {
        var count = 0;
        for (var offset = 0; offset <= haystack.Length - needle.Length; offset++)
        {
            var index = 0;
            for (; index < needle.Length && haystack[offset + index] == needle[index]; index++) { }
            if (index == needle.Length)
            {
                count++;
                offset += needle.Length - 1;
            }
        }
        return count;
    }
}
'@
    }

    return [MarkdownRendererNativeBundleProbe]::Count($haystack, $needle)
}

function Get-PeMachine {
    param([Parameter(Mandatory)][string] $Path)

    $stream = [IO.File]::OpenRead($Path)
    try {
        $reader = [System.Reflection.PortableExecutable.PEReader]::new($stream)
        try { return $reader.PEHeaders.CoffHeader.Machine.ToString() }
        finally { $reader.Dispose() }
    }
    finally {
        $stream.Dispose()
    }
}

function Get-AnyCpuEvidence {
    param([Parameter(Mandatory)][string] $Path)

    $stream = [IO.File]::OpenRead($Path)
    try {
        $reader = [System.Reflection.PortableExecutable.PEReader]::new($stream)
        try {
            $headers = $reader.PEHeaders
            $corHeader = $headers.CorHeader
            if ($null -eq $corHeader) {
                throw "Managed package asset '$Path' has no CLR header."
            }

            $flags = $corHeader.Flags
            $ilOnly = ($flags -band [System.Reflection.PortableExecutable.CorFlags]::ILOnly) -ne 0
            $requires32Bit =
                ($flags -band [System.Reflection.PortableExecutable.CorFlags]::Requires32Bit) -ne 0
            $prefers32Bit =
                ($flags -band [System.Reflection.PortableExecutable.CorFlags]::Prefers32Bit) -ne 0
            $passed = $headers.CoffHeader.Machine.ToString() -eq 'I386' -and
                $headers.PEHeader.Magic.ToString() -eq 'PE32' -and
                $ilOnly -and -not $requires32Bit -and -not $prefers32Bit
            if (-not $passed) {
                throw "Managed package asset '$Path' is not RID-neutral AnyCPU IL."
            }

            return [pscustomobject][ordered]@{
                machine = $headers.CoffHeader.Machine.ToString()
                peMagic = $headers.PEHeader.Magic.ToString()
                corFlags = $flags.ToString()
                ilOnly = $ilOnly
                requires32Bit = $requires32Bit
                prefers32Bit = $prefers32Bit
                bytes = (Get-Item -LiteralPath $Path).Length
                sha256 = Get-Sha256 $Path
                passed = $passed
            }
        }
        finally {
            $reader.Dispose()
        }
    }
    finally {
        $stream.Dispose()
    }
}

function Invoke-CompatibleExecutable {
    param(
        [Parameter(Mandatory)][string] $Path,
        [Parameter(Mandatory)][string] $Rid,
        [Parameter(Mandatory)][string] $HostArchitecture
    )

    $compatible = $Rid -eq ('win-' + $HostArchitecture) -or
        ($HostArchitecture -eq 'x64' -and $Rid -eq 'win-x86')
    if (-not $compatible) {
        return [pscustomobject][ordered]@{
            executed = $false
            exitCode = $null
            output = $null
            reason = "Cross-published $Rid output cannot run on the $HostArchitecture evidence host."
        }
    }

    $output = @(& $Path 2>&1)
    $exitCode = $LASTEXITCODE
    if ($exitCode -ne 0) {
        throw "Deployment smoke '$Path' failed with exit code $exitCode."
    }

    return [pscustomobject][ordered]@{
        executed = $true
        exitCode = $exitCode
        output = ($output -join "`n")
        reason = $null
    }
}

function Get-PackageEvidence {
    param(
        [Parameter(Mandatory)][string] $Directory,
        [Parameter(Mandatory)][string] $Id
    )

    $packageNamePattern = '^{0}\.[0-9]' -f [Regex]::Escape($Id)
    $package = Get-ChildItem -LiteralPath $Directory -Filter '*.nupkg' -File |
        Where-Object {
            $_.Name -notlike '*.symbols.nupkg' -and
            $_.Name -match $packageNamePattern
        } |
        Sort-Object Name |
        Select-Object -First 1
    if ($null -eq $package) {
        throw "NuGet package '$Id' was not produced in '$Directory'."
    }

    $archive = [IO.Compression.ZipFile]::OpenRead($package.FullName)
    try {
        $nuspecEntry = $archive.GetEntry($Id + '.nuspec')
        if ($null -eq $nuspecEntry) { throw "Package '$Id' has no nuspec." }
        $reader = [IO.StreamReader]::new($nuspecEntry.Open())
        try { $nuspec = [xml] $reader.ReadToEnd() }
        finally { $reader.Dispose() }

        return [pscustomobject][ordered]@{
            id = $Id
            version = [string] $nuspec.package.metadata.version
            path = $package.FullName
            compressedBytes = $package.Length
            sha256 = Get-Sha256 $package.FullName
            entries = @($archive.Entries.FullName)
            dependencies = @($nuspec.SelectNodes("//*[local-name()='dependency']") | ForEach-Object {
                [pscustomobject][ordered]@{
                    id = [string] $_.id
                    version = [string] $_.version
                }
            })
        }
    }
    finally {
        $archive.Dispose()
    }
}

function Assert-Dependencies {
    param(
        [Parameter(Mandatory)] $Package,
        [Parameter(Mandatory)][string[]] $Required,
        [string[]] $Forbidden = @()
    )

    $ids = @($Package.dependencies | ForEach-Object { $_.id })
    foreach ($id in $Required) {
        if ($id -notin $ids) {
            throw "Package '$($Package.id)' is missing dependency '$id'."
        }
    }
    foreach ($id in $Forbidden) {
        if ($id -in $ids) {
            throw "Package '$($Package.id)' unexpectedly depends on '$id'."
        }
    }
}

function Assert-PackageEntries {
    param(
        [Parameter(Mandatory)] $Package,
        [Parameter(Mandatory)][string[]] $Required
    )

    foreach ($entry in $Required) {
        if ($entry -notin $Package.entries) {
            throw "Package '$($Package.id)' is missing '$entry'."
        }
    }
    $nativeEntries = @($Package.entries | Where-Object { $_ -match '(?i)^runtimes/.+/native/' })
    if ($nativeEntries.Count -ne 0) {
        throw "Package '$($Package.id)' unexpectedly embeds native assets: $($nativeEntries -join ', ')."
    }
}

function Export-PackageEntry {
    param(
        [Parameter(Mandatory)][string] $PackagePath,
        [Parameter(Mandatory)][string] $EntryPath,
        [Parameter(Mandatory)][string] $DestinationPath
    )

    $archive = [IO.Compression.ZipFile]::OpenRead($PackagePath)
    try {
        $entry = $archive.GetEntry($EntryPath)
        if ($null -eq $entry) {
            throw "Package '$PackagePath' is missing '$EntryPath'."
        }
        [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($DestinationPath)) | Out-Null
        [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $DestinationPath, $true)
    }
    finally {
        $archive.Dispose()
    }
}

