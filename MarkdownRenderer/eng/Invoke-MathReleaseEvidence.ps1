function Invoke-DotNet {
    param([Parameter(Mandatory)][string[]] $Arguments)

    if ($Arguments[0] -eq 'restore') {
        # The evidence source is disposable. Do not require or rewrite its copied
        # lock files, which may have been generated by a different SDK patch.
        $Arguments += @(
            '-p:RestorePackagesWithLockFile=false',
            '-p:RestoreLockedMode=false',
            ("-p:NuGetLockFilePath=$evidenceLockPath")
        )
    }
    & dotnet @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet $($Arguments -join ' ') failed with exit code $LASTEXITCODE."
    }
}

function Get-Sha256 {
    param([Parameter(Mandatory)][string] $Path)

    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Get-PeMachine {
    param([Parameter(Mandatory)][string] $Path)

    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -lt 64 -or $bytes[0] -ne 0x4d -or $bytes[1] -ne 0x5a) {
        throw "Deployment output '$Path' is not an MZ executable."
    }
    $peOffset = [BitConverter]::ToInt32($bytes, 0x3c)
    if ($peOffset -lt 0 -or $peOffset + 6 -gt $bytes.Length -or
        $bytes[$peOffset] -ne 0x50 -or $bytes[$peOffset + 1] -ne 0x45) {
        throw "Deployment output '$Path' has no valid PE signature."
    }
    $machineValue = [BitConverter]::ToUInt16($bytes, $peOffset + 4)
    switch ($machineValue) {
        332 { return 'x86' }
        34404 { return 'x64' }
        43620 { return 'arm64' }
        default { return 'unknown-0x' + $machineValue.ToString('x4') }
    }
}

function Get-VendorAggregate {
    param(
        [Parameter(Mandatory)][string] $ThirdPartyDirectory,
        [Parameter(Mandatory)][string] $ProjectPath
    )

    $root = (Resolve-Path -LiteralPath $ThirdPartyDirectory).Path
    $projectOutput = @(& dotnet msbuild $ProjectPath `
        '-p:Configuration=Release' '-p:Platform=x64' '-getItem:Compile')
    if ($LASTEXITCODE -ne 0) {
        throw 'Could not evaluate the Math project compile allowlist.'
    }
    $evaluatedItems = ($projectOutput -join "`n" | ConvertFrom-Json).Items.Compile
    $paths = [Collections.Generic.List[string]]::new()
    foreach ($item in $evaluatedItems) {
        $fullPath = [string] $item.FullPath
        if ($fullPath.StartsWith($root + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
            $paths.Add($fullPath.Substring($root.Length + 1).Replace('\', '/'))
        }
    }
    @(
        'CSharpMath.Rendering/Reference Fonts/AMS-Capital-Blackboard-Bold.otf',
        'CSharpMath.Rendering/Reference Fonts/cyrillic-modern-nmr10.otf',
        'CSharpMath.Rendering/Reference Fonts/latinmodern-math.otf'
    ) | ForEach-Object { $paths.Add($_) }

    $ordered = [string[]] @($paths.ToArray() | Sort-Object -Unique -CaseSensitive)
    [Array]::Sort($ordered, [StringComparer]::Ordinal)
    $hash = [Security.Cryptography.IncrementalHash]::CreateHash(
        [Security.Cryptography.HashAlgorithmName]::SHA256)
    try {
        foreach ($relative in $ordered) {
            $pathBytes = [Text.Encoding]::UTF8.GetBytes($relative)
            $contentPath = Join-Path $root $relative.Replace('/', '\')
            $contentBytes = [IO.File]::ReadAllBytes($contentPath)
            # Vendor source is text, but the fonts are binary. Normalize only
            # source checkout newlines so Git's CRLF setting cannot alter the
            # audited upstream aggregate.
            if ($relative.EndsWith('.cs', [StringComparison]::OrdinalIgnoreCase)) {
                $content = [Text.Encoding]::UTF8.GetString($contentBytes).Replace("`r`n", "`n", [StringComparison]::Ordinal)
                $contentBytes = [Text.Encoding]::UTF8.GetBytes($content)
            }
            $hash.AppendData([BitConverter]::GetBytes([uint32] $pathBytes.Length))
            $hash.AppendData($pathBytes)
            $hash.AppendData([BitConverter]::GetBytes([uint64] $contentBytes.LongLength))
            $hash.AppendData($contentBytes)
        }
        return [pscustomobject][ordered]@{
            fileCountIncludingFonts = $ordered.Length
            sha256 = [Convert]::ToHexString($hash.GetHashAndReset()).ToLowerInvariant()
            paths = $ordered
        }
    }
    finally {
        $hash.Dispose()
    }
}

function Invoke-CompatibleExecutable {
    param(
        [Parameter(Mandatory)][string] $Path,
        [Parameter(Mandatory)][string] $Rid,
        [Parameter(Mandatory)][string] $HostArchitecture
    )

    $compatible = $Rid -eq ('win-' + $HostArchitecture) -or
        ($HostArchitecture -eq 'x64' -and $Rid -eq 'win-x86')
    if (-not $compatible) {
        return [pscustomobject][ordered]@{
            executed = $false
            exitCode = $null
            output = $null
            reason = "Cross-published $Rid output cannot run on the $HostArchitecture evidence host."
        }
    }

    $output = @(& $Path 2>&1)
    $exitCode = $LASTEXITCODE
    if ($exitCode -ne 0) {
        throw "Deployment smoke '$Path' failed with exit code $exitCode."
    }
    return [pscustomobject][ordered]@{
        executed = $true
        exitCode = $exitCode
        output = ($output -join "`n")
        reason = $null
    }
}

