    schemaVersion = 1
    generatedUtc = [DateTime]::UtcNow.ToString('O', [Globalization.CultureInfo]::InvariantCulture)
    hostArchitecture = $hostArchitecture
    contractTests = [pscustomobject][ordered]@{
        total = [int] $counters.total
        executed = [int] $counters.executed
        passed = [int] $counters.passed
        failed = [int] $counters.failed
        trx = (Join-Path $testResultsDirectory 'math-contracts.trx')
    }
    package = [pscustomobject][ordered]@{
        id = 'MarkdownRenderer.Math'
        version = $packageVersion
        path = $package.FullName
        compressedBytes = $package.Length
        capBytes = $packageCapBytes
        headroomBytes = $packageCapBytes - $package.Length
        managedLibraryBytes = $managedBytes
        nativeAssetCount = $nativeEntries.Count
        packageDependencyCount = $dependencies.Count
        sha256 = Get-Sha256 $package.FullName
    }
    vendorSnapshot = [pscustomobject][ordered]@{
        upstreamCommit = [string] $provenance.upstream.commit
        typographyCommit = [string] $provenance.upstream.typographySubmoduleCommit
        fileCountIncludingFonts = $vendorAggregate.fileCountIncludingFonts
        patchedAggregateSha256 = $vendorAggregate.sha256
        unsupportedGeneralFontReaderCount = $unsupportedVendorPaths.Count
        filesystemWriteSourceCount = $filesystemWriteSources.Count
        provenancePath = $provenancePath
    }
    compliance = [pscustomobject][ordered]@{
        spdx = (Join-Path $complianceDirectory ("MarkdownRenderer.Math.$packageVersion.spdx.json"))
        notices = (Join-Path $complianceDirectory ("MarkdownRenderer.Math.$packageVersion.THIRD-PARTY-NOTICES.md"))
        nativeReport = (Join-Path $complianceDirectory 'native-package-compliance.json')
        reproducibilityManifest = (Join-Path $complianceDirectory 'package-reproducibility.json')
    }
    deployments = @($deployments)
}
