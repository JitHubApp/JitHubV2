    Pop-Location
}

$trx = [xml] (Get-Content -LiteralPath (Join-Path $testResultsDirectory 'math-contracts.trx') -Raw)
$counters = $trx.TestRun.ResultSummary.Counters
if ([int] $counters.failed -ne 0 -or [int] $counters.executed -ne [int] $counters.passed) {
    throw 'Math contract-test evidence contains a failure or non-passing executed test.'
}

$package = Get-ChildItem -LiteralPath $packageDirectory -Filter 'MarkdownRenderer.Math.*.nupkg' -File |
    Where-Object { $_.Name -notlike '*.symbols.nupkg' } |
    Sort-Object LastWriteTimeUtc -Descending |
    Select-Object -First 1
if ($null -eq $package) { throw 'The Math NuGet package was not produced.' }

$packageCapBytes = [long] (2.3MB)
if ($package.Length -gt $packageCapBytes) {
    throw "MarkdownRenderer.Math is $($package.Length) bytes; the 2.3 MiB gate is $packageCapBytes bytes."
}

$requiredPackageEntries = @(
    'LICENSE',
    'icon-192.png',
    'README.md',
    'THIRD-PARTY-NOTICES.md',
    'UPSTREAM-PATCHES.md',
    'licenses/CSHARPMATH-LICENSE.txt',
    'licenses/TYPOGRAPHY-LICENSE.md',
    'licenses/GUST-FONT-LICENSE.txt',
    'licenses/OFL-1.1.txt',
    'licenses/PROVENANCE.json',
    'lib/net10.0-windows10.0.26100/MarkdownRenderer.Math.dll',
    'lib/net10.0-windows10.0.26100/MarkdownRenderer.Math.xml'
)
$archive = [IO.Compression.ZipFile]::OpenRead($package.FullName)
try {
    $entryNames = @($archive.Entries.FullName)
    foreach ($required in $requiredPackageEntries) {
        if ($required -notin $entryNames) { throw "Math package is missing '$required'." }
    }
    $nativeEntries = @($entryNames | Where-Object { $_ -match '(?i)^runtimes/.+/native/' })
    if ($nativeEntries.Count -ne 0) {
        throw "Math package unexpectedly contains native payload: $($nativeEntries -join ', ')."
    }
    $managedEntry = $archive.GetEntry('lib/net10.0-windows10.0.26100/MarkdownRenderer.Math.dll')
    if ($null -eq $managedEntry) { throw 'Math package has no managed library entry.' }
    $managedBytes = $managedEntry.Length

    $nuspecEntry = $archive.GetEntry('MarkdownRenderer.Math.nuspec')
    if ($null -eq $nuspecEntry) { throw 'Math package has no nuspec.' }
    $reader = [IO.StreamReader]::new($nuspecEntry.Open())
    try { $nuspec = [xml] $reader.ReadToEnd() } finally { $reader.Dispose() }
    $packageVersion = [string] $nuspec.package.metadata.version
    $metadata = $nuspec.package.metadata
    if ([string] $metadata.license.type -ne 'expression' -or [string] $metadata.license.InnerText -ne 'MIT') {
        throw 'Math package must declare the MIT license expression.'
    }
    if ([string] $metadata.icon -ne 'icon-192.png' -or
        [string] $metadata.projectUrl -ne 'https://github.com/JitHubApp/JitHubV2/tree/main/docs/markdown-renderer') {
        throw 'Math package icon/project URL metadata is incomplete.'
    }
    if ([string] $metadata.repository.type -ne 'git' -or
        [string] $metadata.repository.url -ne 'https://github.com/JitHubApp/JitHubV2') {
        throw 'Math package repository/SourceLink metadata is incomplete.'
    }
    $dependencies = @($nuspec.SelectNodes("//*[local-name()='dependency']"))
    if ($dependencies.Count -ne 1 -or $dependencies[0].id -ne 'MarkdownRenderer.Core') {
        throw "Math package must declare exactly one MarkdownRenderer.Core package dependency; found $($dependencies.Count)."
    }
}
finally {
    $archive.Dispose()
}

$thirdPartyDirectory = Join-Path $markdownRoot 'MarkdownRenderer.Math\ThirdParty'
$provenancePath = Join-Path $thirdPartyDirectory 'PROVENANCE.json'
$provenance = Get-Content -LiteralPath $provenancePath -Raw | ConvertFrom-Json
$mathProject = Join-Path $markdownRoot 'MarkdownRenderer.Math\MarkdownRenderer.Math.csproj'
$vendorAggregate = Get-VendorAggregate `
    -ThirdPartyDirectory $thirdPartyDirectory `
    -ProjectPath $mathProject
if ($vendorAggregate.fileCountIncludingFonts -ne [int] $provenance.compiledSnapshot.fileCountIncludingFonts -or
    $vendorAggregate.sha256 -ne [string] $provenance.compiledSnapshot.patchedAggregateSha256) {
    throw 'The compiled Math vendor snapshot no longer matches PROVENANCE.json.'
}
$unsupportedVendorPaths = @($vendorAggregate.paths | Where-Object {
    $_ -match '(?i)(WebFont|BitmapAndSvgFonts|Tables\.Variations|Tables\.TrueType|TrueTypeInterperter|Tables\.Others)'
})
if ($unsupportedVendorPaths.Count -ne 0) {
    throw "The Math compile allowlist contains unsupported general font readers: $($unsupportedVendorPaths -join ', ')."
}
$filesystemWriteSources = @($vendorAggregate.paths | Where-Object { $_ -like '*.cs' } | Where-Object {
    $candidate = Join-Path $thirdPartyDirectory $_.Replace('/', '\')
    Select-String -LiteralPath $candidate -Pattern 'File.WriteAllText' -Quiet
})
if ($filesystemWriteSources.Count -ne 0) {
    throw "The Math compile allowlist contains a filesystem write path: $($filesystemWriteSources -join ', ')."
}
foreach ($font in @($provenance.fonts)) {
    $fontPath = Join-Path $thirdPartyDirectory ('CSharpMath.Rendering\Reference Fonts\' + [string] $font.file)
    if ((Get-Sha256 $fontPath) -ne [string] $font.sha256) {
        throw "Hash mismatch for audited font '$($font.file)'."
    }
}

