        if ($entry.CompressedLength -gt $nativeCapBytes) {
            throw "Selected-RID asset '$($entry.FullName)' exceeds the 400 KiB compressed cap."
        }
        $expected = $provenanceByPath[$entry.FullName]
        if ($null -eq $expected) { throw "No provenance record exists for '$($entry.FullName)'." }
        $stream = $entry.Open()
        try { $sha256 = Get-StreamSha256 -Stream $stream } finally { $stream.Dispose() }
        if ($entry.Length -ne [long] $expected.bytes -or $sha256 -ne [string] $expected.sha256) {
            throw "Packaged asset '$($entry.FullName)' differs from its pinned provenance."
        }
        $nativeAssets.Add([pscustomobject][ordered]@{
            path = $entry.FullName
            peMachine = [string] $expected.peMachine
            uncompressedBytes = $entry.Length
            compressedBytes = $entry.CompressedLength
            capBytes = $nativeCapBytes
            headroomBytes = $nativeCapBytes - $entry.CompressedLength
            sha256 = $sha256
        })
