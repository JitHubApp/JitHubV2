            -Path $executable -Rid $target.Rid -HostArchitecture $hostArchitecture
        $deployments.Add([pscustomobject][ordered]@{
            mode = $mode
            rid = $target.Rid
            executableMachine = $executableMachine
            nativeMachine = $nativeMachine
