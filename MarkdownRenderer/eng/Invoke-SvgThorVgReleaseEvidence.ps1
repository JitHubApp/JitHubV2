function Invoke-DotNet {
    param([Parameter(Mandatory)][string[]] $Arguments)

    if ($Arguments[0] -eq 'restore') {
        # The evidence source is disposable. Do not require or rewrite its copied
        # lock files, which may have been generated by a different SDK patch.
        $Arguments += @(
            '-p:RestorePackagesWithLockFile=false',
            '-p:RestoreLockedMode=false',
            ("-p:NuGetLockFilePath=$evidenceLockPath")
        )
    }
    & dotnet @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet $($Arguments -join ' ') failed with exit code $LASTEXITCODE."
    }
}

function Get-Sha256 {
    param([Parameter(Mandatory)][string] $Path)

    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Get-StreamSha256 {
    param([Parameter(Mandatory)][IO.Stream] $Stream)

    $hash = [Security.Cryptography.SHA256]::Create()
    try { return [Convert]::ToHexString($hash.ComputeHash($Stream)).ToLowerInvariant() }
    finally { $hash.Dispose() }
}

function Get-PeMachine {
    param([Parameter(Mandatory)][string] $Path)

    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -lt 64 -or $bytes[0] -ne 0x4d -or $bytes[1] -ne 0x5a) {
        throw "'$Path' is not an MZ executable."
    }
    $peOffset = [BitConverter]::ToInt32($bytes, 0x3c)
    if ($peOffset -lt 0 -or $peOffset + 6 -gt $bytes.Length -or
        $bytes[$peOffset] -ne 0x50 -or $bytes[$peOffset + 1] -ne 0x45) {
        throw "'$Path' has no valid PE signature."
    }
    switch ([BitConverter]::ToUInt16($bytes, $peOffset + 4)) {
        332 { return 'x86' }
        34404 { return 'x64' }
        43620 { return 'arm64' }
        default { return 'unknown' }
    }
}

function Get-ManagedPeEvidence {
    param([Parameter(Mandatory)][string] $Path)

    $stream = [IO.File]::OpenRead($Path)
    $reader = $null
    try {
        $reader = [Reflection.PortableExecutable.PEReader]::new($stream)
        $headers = $reader.PEHeaders
        $corHeader = $headers.CorHeader
        if ($null -eq $corHeader) { throw "'$Path' is not a managed PE." }
        $flags = [int] $corHeader.Flags
        $machine = $headers.CoffHeader.Machine.ToString()
        $magic = $headers.PEHeader.Magic.ToString()
        $ilOnly = ($flags -band 1) -ne 0
        $requires32Bit = ($flags -band 2) -ne 0
        $prefers32Bit = ($flags -band 0x20000) -ne 0
        return [pscustomobject][ordered]@{
            machine = $machine
            peMagic = $magic
            ilOnly = $ilOnly
            requires32Bit = $requires32Bit
            prefers32Bit = $prefers32Bit
            anyCpu = $machine -eq 'I386' -and $magic -eq 'PE32' -and
                $ilOnly -and -not $requires32Bit -and -not $prefers32Bit
        }
    }
    finally {
        if ($null -ne $reader) { $reader.Dispose() }
        else { $stream.Dispose() }
    }
}

function Invoke-CompatibleExecutable {
    param(
        [Parameter(Mandatory)][string] $Path,
        [Parameter(Mandatory)][string] $Rid,
        [Parameter(Mandatory)][string] $HostArchitecture,
        [string[]] $Arguments = @()
    )

    $compatible = $Rid -eq ('win-' + $HostArchitecture) -or
        ($HostArchitecture -eq 'x64' -and $Rid -eq 'win-x86')
    if (-not $compatible) {
        return [pscustomobject][ordered]@{
            executed = $false
            exitCode = $null
            output = $null
            reason = "Cross-published $Rid output cannot run on the $HostArchitecture evidence host."
        }
    }

    $output = @(& $Path @Arguments 2>&1)
    $exitCode = $LASTEXITCODE
    if ($exitCode -ne 0) {
        throw "Deployment smoke '$Path' failed with exit code $exitCode. Output: $($output -join "`n")"
    }
    return [pscustomobject][ordered]@{
        executed = $true
        exitCode = $exitCode
        output = ($output -join "`n")
        reason = $null
    }
}

function Copy-DeploymentWithoutThorVg {
    param(
        [Parameter(Mandatory)][string] $Source,
        [Parameter(Mandatory)][string] $Destination
    )

    [IO.Directory]::CreateDirectory($Destination) | Out-Null
    foreach ($item in Get-ChildItem -LiteralPath $Source -Force) {
        if ($item.Name -ieq 'thorvg.dll') { continue }
        Copy-Item -LiteralPath $item.FullName -Destination $Destination -Recurse
    }
}

